const find=q=>result.qa.find(x=>x.question===q);
assert.ok(find('Fins quan hem de pagar?').text.includes('18 de novembre'));
assert.deepEqual(find('Fins quan hem de pagar?').sources.map(x=>x.id),['mail-03','wa-07','mail-20']);
